import React from 'react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';

const reads = vi.hoisted(() => ({ catalog: vi.fn(), speed: vi.fn(), showcase: vi.fn(), usage: vi.fn() }));
const writes = vi.hoisted(() => ({ selection: vi.fn() }));
vi.mock('../../../services/modelCatalog', async (original) => ({ ...await original<object>(), fetchModelCatalog: reads.catalog }));
vi.mock('../../../services/modelSpeed', async (original) => ({ ...await original<object>(), fetchModelSpeedReport: reads.speed }));
vi.mock('../../../services/modelShowcase', async (original) => ({ ...await original<object>(), fetchModelShowcase: reads.showcase }));
vi.mock('../../../services/modelUsageTrends', async (original) => ({ ...await original<object>(), fetchModelUsageMonthly: reads.usage }));
vi.mock('../../../services/modelSelection', async (original) => ({ ...await original<object>(), setSelectedModel: writes.selection }));

import scene, { MODELS_QA_DATA } from './models';
import { focusedTextModels, modelMaker } from '../../../components/models/workspaceData';

afterEach(() => { cleanup(); vi.clearAllMocks(); });

describe('Models app QA scene', () => {
  it('renders five cards with a clear fixture notice, missing-data and source-failure states without fetching', () => {
    render(<scene.Scene />);
    expect(screen.getAllByRole('main')).toHaveLength(1);
    expect(screen.getAllByRole('article')).toHaveLength(5);
    expect(screen.getByText('QA fixture — all examples and measurements below are synthetic.')).toBeTruthy();
    expect(screen.getByText('No attributed output yet')).toBeTruthy();
    expect(screen.getAllByText('Examples couldn’t load').length).toBeGreaterThan(0);
    for (const request of Object.values(reads)) expect(request).not.toHaveBeenCalled();
    const fixtureSvg = decodeURIComponent(MODELS_QA_DATA.showcase.rows[0].examples[0].url);
    expect(fixtureSvg).toContain('NOT GENERATED BY THIS MODEL');
  });

  it('includes all ten makers and switches to known, unknown and free text-price fixtures offline', () => {
    const models = focusedTextModels(MODELS_QA_DATA.catalog.models);
    expect(new Set(models.map((model) => modelMaker(model).id)).size).toBe(10);
    render(<scene.Scene />);
    fireEvent.click(screen.getByRole('tab', { name: 'Language models' }));
    expect(screen.getByText('10 featured providers')).toBeTruthy();
    expect(screen.getAllByText('QA OpenAI model').length).toBeGreaterThan(0);
    expect(screen.getAllByText('Not reported').length).toBeGreaterThan(0);
    expect(screen.getAllByText('$0').length).toBeGreaterThan(0);
    expect(screen.getAllByText('$3.00').length).toBeGreaterThan(0);
    for (const request of Object.values(reads)) expect(request).not.toHaveBeenCalled();
  });

  it('keeps preview connections and preference writes disabled', () => {
    render(<scene.Scene />);
    expect((screen.getByRole('button', { name: 'Connections' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByRole('tab', { name: 'Language models' }));
    fireEvent.click(screen.getByRole('button', { name: 'Details for QA OpenAI model' }));
    const select = screen.getByRole('button', { name: 'Set text default' }) as HTMLButtonElement;
    expect(select.disabled).toBe(true);
    fireEvent.click(select);
    expect(writes.selection).not.toHaveBeenCalled();
  });

  it('shows usage fixtures without reading the live usage service, including refresh', async () => {
    render(<scene.Scene />);
    fireEvent.click(screen.getByRole('tab', { name: 'Usage' }));
    expect(await screen.findByRole('heading', { name: 'Recorded model usage' })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Refresh usage' }));
    for (const request of Object.values(reads)) expect(request).not.toHaveBeenCalled();
  });
});
