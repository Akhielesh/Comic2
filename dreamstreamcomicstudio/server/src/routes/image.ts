const replayImage = (res: Response, cacheKey: string, requestHash: string): Promise<IdempotencyResult> | undefined => {
  const now = Date.now();
  const cached = idempotencyResponseCache.get(cacheKey);
  if (cached && cached.expiresAt > now) {
    if (cached.requestHash !== requestHash) {
      throw toIdempotencyConflictError();
    }
    res.setHeader('Idempotency-Replayed', 'true');
    if (cached.unconfirmed) throw unconfirmedImage();
    if (cached.evicted) throw Object.assign(new Error('This image action already completed. Its response data is no longer available.'), {
      status: 410, publicCode: 'IMAGE_RESULT_EXPIRED'
    });
    return Promise.resolve(cached.response);
  }
  if (cached) forgetImageAction(cacheKey);

  const pending = idempotencyInFlight.get(cacheKey);
  if (pending) {
    if (pending.requestHash !== requestHash) throw toIdempotencyConflictError();
    const leave = pending.clients.watch(res);
    res.setHeader('Idempotency-Replayed', 'true');
    return pending.promise.then(r => r.response).catch(err => {
      if (err instanceof StudioError && err.code === 'BUSY') {
        res.setHeader('Retry-After', '10');
        throw Object.assign(err, { publicCode: 'GENERATION_BUSY' });
      }
      throw err;
    }).finally(leave);
  }
};

const withIdempotency = async (
  req: Request,
  res: Response,
  scope: string,
  provider: Parameters<typeof hasByokForProvider>[1],
  operation: (signal: AbortSignal) => Promise<IdempotencyResult>
) => {
  const headerKey = normalizeIdempotencyKey(req.header('Idempotency-Key'));
  const actor = req.user?.id || req.ip || 'anonymous';
  const admitted = async (clients: ImageClients) => {
    // Retained JSON, including inline references, is bounded independently of the task count.
    const length = Number(req.header('Content-Length'));
    const bytes = length > 0 && !req.header('Content-Encoding') ? length : Buffer.byteLength(JSON.stringify(req.body ?? {}));
    try {
      return await comicImageCapacity.run(actor, clients.controller.signal, () => operation(clients.controller.signal), {
        bytes, waitMs: 45_000, ownKey: hasByokForProvider(req, provider)
      });
    } catch (err) {
      if (err instanceof StudioError && err.code === 'BUSY') {
        res.setHeader('Retry-After', '10');
        throw Object.assign(err, { publicCode: 'GENERATION_BUSY' });
      }
      throw err;
    }
  };
  if (!headerKey) {
    const clients = new ImageClients();
    const leave = clients.watch(res);
    try { return await admitted(clients); }
    finally { leave(); }
  }

  const cacheKey = `${scope}:${actor}:${headerKey}`;
  const requestHash = hashPayload(req.body);
  const now = Date.now();

  idempotencyOperationCount += 1;
  if (idempotencyOperationCount % 100 === 0) {
    cleanupExpiredIdempotencyRecords(now);
    idempotencyOperationCount = 0;
  }

  const replay = replayImage(res, cacheKey, requestHash);
  if (replay) return replay;
  const clients = new ImageClients();
  const leave = clients.watch(res);
  const executionPromise = (async () => {
    let response: IdempotencyResult;
    try {
      response = await admitted(clients);
    } catch (err) {
      if (scope === 'image:standalone' && res.locals.imageResultUnconfirmed) {
        rememberImageAction(cacheKey, { requestHash, response: {}, unconfirmed: true, expiresAt: Date.now() + IDEMPOTENCY_TTL_MS });
        throw unconfirmedImage();
      }
      throw err;
    }
    const record: IdempotencyRecord = {
      requestHash,
      response,
      expiresAt: Date.now() + IDEMPOTENCY_TTL_MS
    };
    rememberImageAction(cacheKey, record);
    return record;
  })();

  idempotencyInFlight.set(cacheKey, { requestHash, promise: executionPromise, clients });
  res.setHeader('Idempotency-Replayed', 'false');

  try {
    const resolved = await executionPromise;
    return resolved.response;
  } finally {
    leave();
    idempotencyInFlight.delete(cacheKey);
  }
};

