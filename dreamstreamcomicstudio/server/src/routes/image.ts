type IdempotencyResult = Record<string, unknown>;
type IdempotencyRecord = {
  expiresAt: number;
  requestHash: string;
  response: IdempotencyResult;
  unconfirmed?: boolean;
  evicted?: boolean;
  bytes?: number;
};

const idempotencyResponseCache = new Map<string, IdempotencyRecord>();
// Identical HTTP retries share a queued operation. Only the last still-interested
// client leaving can abandon it before dispatch; accepted work is saved normally.
class ImageClients {
  private count = 0;
  readonly controller = new AbortController();

  watch(res: Response): () => void {
    this.count++;
    let attached = true;
    const leave = () => {
      if (!attached) return;
      attached = false;
      res.off('close', leave);
      if (--this.count === 0) this.controller.abort();
    };
    if (res.destroyed) leave();
    else res.once('close', leave);
    return leave;
  }
}
const idempotencyInFlight = new Map<string, { requestHash: string; promise: Promise<IdempotencyRecord>; clients: ImageClients }>();
let idempotencyOperationCount = 0;
const MAX_IDEMPOTENCY_CACHE_BYTES = 2_000_000;
const MAX_IDEMPOTENCY_RESULT_BYTES = 24 * 1024 * 1024;
let resultBytes = 0;
const MAX_IDEMPOTENCY_CACHE_ENTRIES = 1000; // hard cap so a burst of unique keys can't grow memory unbounded

const forgetImageAction = (key: string) => {
  resultBytes -= idempotencyResponseCache.get(key)?.bytes ?? 0;
  idempotencyResponseCache.delete(key);
};

const cleanupExpiredIdempotencyRecords = (now: number) => {
  for (const [key, record] of idempotencyResponseCache) {
    if (record.expiresAt <= now) forgetImageAction(key);
  }
};

// Prefer the existing private signed result for large renders. If a legacy test
// action generated bytes without saving, keep its identity after evicting the bytes:
// an HTTP retry must never purchase a second render merely because memory is full.
const compactImageAction = (record: IdempotencyRecord): IdempotencyRecord => {
  const { imageId, imageUrl, ...metadata } = record.response;
  if (!imageId || !imageUrl) return { ...record, response: {}, bytes: 0, evicted: true };
  delete metadata.dataUrl;
  const response = { ...metadata, imageId, imageUrl };
  return { ...record, response, bytes: Buffer.byteLength(JSON.stringify(response)) };
};

const rememberImageAction = (key: string, value: IdempotencyRecord) => {
  const { dataUrl, ...rest } = value.response;
  const bytes = Buffer.byteLength(JSON.stringify(rest)) + (typeof dataUrl === 'string' ? Buffer.byteLength(dataUrl) : 0);
  let record: IdempotencyRecord = { ...value, bytes };
  if (bytes > MAX_IDEMPOTENCY_CACHE_BYTES) record = compactImageAction(record);
  if (idempotencyResponseCache.has(key)) forgetImageAction(key);
  while (idempotencyResponseCache.size >= MAX_IDEMPOTENCY_CACHE_ENTRIES) forgetImageAction(idempotencyResponseCache.keys().next().value!);
  for (const [oldKey, old] of idempotencyResponseCache) {
    if (resultBytes + record.bytes! <= MAX_IDEMPOTENCY_RESULT_BYTES) break;
    if (!old.bytes) continue;
    const compact = compactImageAction(old);
    // A very large non-image metadata result can also be evicted safely.
    const kept = compact.bytes! < old.bytes ? compact : { ...old, response: {}, bytes: 0, evicted: true };
    resultBytes += kept.bytes! - old.bytes;
    idempotencyResponseCache.set(oldKey, kept);
  }
  if (record.bytes! > MAX_IDEMPOTENCY_RESULT_BYTES) record = { ...record, response: {}, bytes: 0, evicted: true };
  resultBytes += record.bytes!;
  idempotencyResponseCache.set(key, record);
};

const normalizeIdempotencyKey = (value?: string | null) => {
  if (!value) return null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  return trimmed.slice(0, 128);
};

const hashPayload = (payload: unknown) =>
  crypto
    .createHash('sha256')
    .update(JSON.stringify(payload ?? null))
    .digest('hex');

const toIdempotencyConflictError = () => {
  const error = new Error('Idempotency key already used with a different payload.') as Error & {
    status?: number;
    publicCode?: string;
  };
  error.status = 409;
  error.publicCode = 'CONFLICT';
  return error;
};

